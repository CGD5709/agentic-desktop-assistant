"""
Action node responsible for dispatching tool calls to the execution service over RabbitMQ.
"""
import time
from typing import Any, Dict, Final, List
import uuid
from langchain_core.messages import AIMessage, ToolMessage

from ..models import (
    AgentState,
    EventEnvelope,
    EventMetadata,
    EventType,
    ToolExecutionRequestPayload,
)
from rabbitmq import RabbitMQClient

# Metadata identifiers and RPC conventions
DEFAULT_SOURCE_ID: Final[str] = "reasoning-engine"
TOOL_REQUEST_ROUTING_KEY_PREFIX: Final[str] = "tool.request."
STATUS_SUCCESS: Final[str] = "SUCCESS"
DEFAULT_TOOL_SUCCESS_OUTPUT: Final[str] = "Action completed."
MS_PER_SECOND: Final[int] = 1000


class ActionNode:
    """
    Dispatches tool execution requests generated by the agent model to the
    external execution service via RabbitMQ RPC and collects the resulting ToolMessages.
    """

    def __init__(self, mq_client: RabbitMQClient) -> None:
        """
        Initialize the action node with injected messaging client.

        Args:
            mq_client: RabbitMQ RPC messaging client.
        """
        self._mq_client = mq_client

    async def __call__(self, state: AgentState) -> Dict[str, Any]:
        """
        Dispatch all tool calls from the latest AI message and gather execution responses.

        Args:
            state: Current agent state dictionary.

        Returns:
            Dictionary containing the list of executed ToolMessage responses.

        Raises:
            TypeError: If the last message in state is not an AIMessage.
        """
        messages = state.get("messages", [])
        if not messages:
            return {"messages": []}

        last_message = messages[-1]
        if not isinstance(last_message, AIMessage):
            raise TypeError(
                f"Expected last message in state to be an AIMessage, but received {type(last_message).__name__}"
            )

        tool_messages: List[ToolMessage] = []

        for tool_call in last_message.tool_calls:
            tool_name = tool_call["name"]
            tool_args = tool_call["args"]
            tool_call_id = tool_call.get("id") or str(uuid.uuid4())

            request_payload = ToolExecutionRequestPayload(
                toolName=tool_name, arguments=tool_args
            )
            envelope = EventEnvelope(
                metadata=EventMetadata(
                    eventId=str(uuid.uuid4()),
                    correlationId=str(tool_call_id),
                    timestamp=int(time.time() * MS_PER_SECOND),
                    source=DEFAULT_SOURCE_ID,
                    eventType=EventType.EXECUTION_REQUEST,
                ),
                payload=request_payload.model_dump(by_alias=True),
            )

            routing_key = f"{TOOL_REQUEST_ROUTING_KEY_PREFIX}{tool_name}"

            # TODO: Replace standard print statement with centralized logger
            print(f" 🚀 [RabbitMQ] Dispatching execution request for: {tool_name}")

            raw_response = await self._mq_client.send_and_wait(routing_key, envelope)

            if raw_response is None or not isinstance(raw_response, dict):
                result_text = f"Error: No response received from execution service for tool '{tool_name}'."
            else:
                payload = raw_response.get("payload", {})
                status = payload.get("status", STATUS_SUCCESS)
                output = payload.get("output", DEFAULT_TOOL_SUCCESS_OUTPUT)
                result_text = output if status == STATUS_SUCCESS else f"Error: {output}"

            tool_messages.append(
                ToolMessage(content=result_text, tool_call_id=tool_call_id)
            )

        return {"messages": tool_messages}


__all__ = [
    "DEFAULT_SOURCE_ID",
    "TOOL_REQUEST_ROUTING_KEY_PREFIX",
    "STATUS_SUCCESS",
    "DEFAULT_TOOL_SUCCESS_OUTPUT",
    "MS_PER_SECOND",
    "ActionNode",
]
